  /**
   * Creates an element. Example:
   *   h('a', { className: 'link', href: '/x', text: 'Hello' })
   * Children can be elements or strings; null/false children are skipped.
   */
  function h(tag, props, children) {
    const node = document.createElement(tag);

    Object.entries(props || {}).forEach(([key, value]) => {
      if (value === null || value === undefined || value === false) return;
      if (key === 'className') node.className = value;
      else if (key === 'text') node.textContent = value;
      else if (key === 'html') node.innerHTML = value; // only used with the trusted ICONS above
      else node.setAttribute(key, value === true ? '' : value);
    });

    [].concat(children || []).forEach((child) => {
      if (child === null || child === undefined || child === false) return;
      node.append(child);
    });

    return node;
  }

  /**
   * Picks the right language from a bilingual field.
   * Returns { text, lang } — lang is set only when we had to fall back to
   * the other language, so the element can be marked with the correct lang/dir.
   */
  function localize(field) {
    if (field === null || field === undefined || field === '') return null;
    if (typeof field !== 'object') return { text: String(field), lang: null };
    if (field[LANG]) return { text: field[LANG], lang: null };
    if (field[OTHER_LANG]) return { text: field[OTHER_LANG], lang: OTHER_LANG };
    return null;
  }

  /** True when this bilingual field exists but lacks the current language. */
  function isMissingTranslation(field) {
    const value = localize(field);
    return Boolean(value && value.lang);
  }

  /** An inline span marked with another language, so the browser shapes and orders it correctly. */
  function otherLanguageSpan(text, lang) {
    return h('span', { lang, dir: lang === 'ar' ? 'rtl' : 'ltr', text });
  }

  /**
   * Builds an element containing localized text. When the text fell back to
   * the other language, it is wrapped in a lang/dir span: the block keeps the
   * page's alignment while the words themselves read in the right direction.
   */
  function textElement(tag, className, field) {
    const value = localize(field);
    if (!value) return null;
    return h(tag, { className }, value.lang ? otherLanguageSpan(value.text, value.lang) : value.text);
  }

  /** "Sample entry" and "Translation needed" labels. */
  function statusTags(item, translatableFields) {
    const tags = [];
    if (item.sample) tags.push(h('span', { className: 'tag', text: T.sample }));
    if (translatableFields.some(isMissingTranslation)) {
      tags.push(h('span', { className: 'tag tag-translation', text: T.translationNeeded }));
    }
    return tags;
  }

